/**
 * Scans public/images and writes src/content/media-manifest.ts with the intrinsic size and a
 * tiny blurred placeholder for every image. Run `npm run media:manifest` after adding images.
 */
import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const imagesDir = path.join(root, "public", "images");
const outFile = path.join(root, "src", "content", "media-manifest.ts");
const supported = /\.(webp|jpe?g|png|avif)$/i;

async function walk(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map((entry) => {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) return walk(full);
      return supported.test(entry.name) ? [full] : [];
    }),
  );
  return nested.flat();
}

const files = (await walk(imagesDir)).sort();
const rows = [];

for (const file of files) {
  const { width, height } = await sharp(file).metadata();
  const blur = await sharp(file).resize(16).webp({ quality: 40 }).toBuffer();
  const src = "/" + path.relative(path.join(root, "public"), file).split(path.sep).join("/");
  rows.push(
    `  "${src}": { width: ${width}, height: ${height}, blurDataURL: "data:image/webp;base64,${blur.toString("base64")}" },`,
  );
}

const source = `// Generated by scripts/generate-media-manifest.mjs — do not edit by hand.

export const mediaManifest = {
${rows.join("\n")}
} as const;

export type ImagePath = keyof typeof mediaManifest;
`;

await fs.writeFile(outFile, source);
console.log(`media-manifest: ${rows.length} images`);
